import path from 'path';
import {
  ToolStepEvent,
  TurnUsageMetrics,
  UsageInformation,
} from '../shared/types.js';
import { AgyStreamCallbacks } from './agyAdapter.js';

/**
 * Separate Demo / Fallback Adapter.
 * Strictly isolated from the real Antigravity CLI adapter so simulated behavior
 * is never confused with real Antigravity data. Every response and metric is
 * explicitly tagged as simulated (`isSimulated: true`).
 */
export class DemoAgentAdapter {
  public getDemoUsageInformation(selectedModel: string): UsageInformation {
    return {
      state: 'UNAVAILABLE',
      provider: 'demo-simulated',
      isSimulated: true,
      currentModel: `${selectedModel} [DEMO]`,
      currentModelDisplayName: 'Demo Simulated Assistant (Offline Fallback)',
      lastTurnTokens: null,
      sessionTotalTokens: {
        inputTokens: 0,
        outputTokens: 0,
        thinkingTokens: 0,
        cacheReadTokens: 0,
        totalTokens: 0,
      },
      contextWindow: {
        status: 'UNAVAILABLE',
        usedTokens: null,
        capacityTokens: null,
        percentUsed: null,
        note: 'Demo Mode active — no real Antigravity context window is consumed.',
      },
      quota: {
        status: 'UNAVAILABLE',
        primaryBucketName: null,
        primaryRemainingPercent: null,
        primaryResetTime: null,
        groups: [],
        description:
          'Demo Mode is active. Switch to Real Antigravity CLI (agy) mode in the toolbar to view actual account quota and token usage.',
      },
      lastUpdatedAt: new Date().toISOString(),
      isStale: false,
      statusMessage: 'DEMO MODE — Real Antigravity usage metrics are not fabricated in demo mode',
    };
  }

  public streamDemoPrompt(options: {
    prompt: string;
    projectDir: string | null;
    callbacks: AgyStreamCallbacks;
  }): { cancel: () => void } {
    let cancelled = false;
    const timers: NodeJS.Timeout[] = [];
    const demoConvId = `demo-${Date.now()}`;
    const projectLabel = options.projectDir
      ? path.basename(options.projectDir) || options.projectDir
      : 'No Project Selected';

    timers.push(
      setTimeout(() => {
        if (cancelled) return;
        options.callbacks.onInit({
          conversationId: demoConvId,
          model: 'demo-simulated-agent',
          cwd: options.projectDir || process.cwd(),
        });
        options.callbacks.onThinkingDelta(
          `[DEMO SIMULATION] Inspecting request for workspace "${projectLabel}"...`
        );
      }, 250)
    );

    timers.push(
      setTimeout(() => {
        if (cancelled) return;
        const step: ToolStepEvent = {
          stepIndex: 1,
          toolName: 'simulated_workspace_scan',
          state: 'DONE',
          parameters: {
            workspace: options.projectDir || '(none)',
            note: 'SIMULATED DEMO EVENT — No real command was executed',
          },
          durationSeconds: 0.4,
        };
        options.callbacks.onToolStep(step);
      }, 750)
    );

    const responseChunks = [
      `> **[DEMO MODE — SIMULATED RESPONSE]**\n` +
        `> This response was generated by the built-in offline **Demo Adapter**, not by a live Antigravity agent session.\n\n`,
      `### Workspace Context\n` +
        `- **Selected Project**: \`${options.projectDir || 'None selected'}\`\n` +
        `- **Your Prompt**: "${options.prompt.slice(0, 140)}${options.prompt.length > 140 ? '...' : ''}"\n\n`,
      `### Sample Code Snippet\n` +
        '```typescript\n' +
        '// [DEMO] Example TypeScript helper for The Virtual Office\n' +
        'export function greetWorkspace(projectName: string): string {\n' +
        '  return `Connected to ${projectName} inside The Virtual Office!`;\n' +
        '}\n' +
        '```\n\n' +
        `To interact with your real authenticated **Antigravity CLI (\`agy\`)**, switch the adapter toggle in the top toolbar to **Real Antigravity CLI**.`,
    ];

    responseChunks.forEach((chunk, idx) => {
      timers.push(
        setTimeout(() => {
          if (cancelled) return;
          options.callbacks.onTextDelta(chunk);
        }, 1100 + idx * 350)
      );
    });

    timers.push(
      setTimeout(() => {
        if (cancelled) return;
        const zeroUsage: TurnUsageMetrics = {
          inputTokens: 0,
          outputTokens: 0,
          thinkingTokens: 0,
          cacheReadTokens: 0,
          totalTokens: 0,
        };
        options.callbacks.onComplete({
          conversationId: demoConvId,
          response: responseChunks.join(''),
          durationSeconds: 1.8,
          usage: zeroUsage,
        });
      }, 2300)
    );

    return {
      cancel: () => {
        cancelled = true;
        for (const t of timers) clearTimeout(t);
      },
    };
  }
}
